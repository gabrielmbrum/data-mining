def calibrate_and_run_dbscan(
    features: dict,
    output_dir: Path,
    k_neighbor: int = 5,
    random_state: int = 42,
) -> dict:
    """
    Implements DBSCAN density-based clustering with hyperparameter calibration
    via the k-distance graph, following Tan et al. (Lecture Notes, slides 93-94).
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    print("\n--- Running DBSCAN Calibration & Clustering ---")

    # We evaluate 1D VRR and 2D GASF
    targets = [
        ("1D_VRR", features["1D_VRR"]),
        ("2D_GASF", features["2D_GASF"]),
    ]

    fig, axes = plt.subplots(1, 2, figsize=(12, 4.5))
    results = {}

    for i, (name, X) in enumerate(targets):
        # Calculate k-distances
        nbrs = NearestNeighbors(n_neighbors=k_neighbor).fit(X)
        distances, _ = nbrs.kneighbors(X)
        k_distances = np.sort(distances[:, -1])[::-1]  # Descending order

        ax = axes[i]
        ax.plot(k_distances, color="#1f77b4", linewidth=1.8)
        ax.set_title(f"Gráfico de k-distância ({k_neighbor}º vizinho) - {name}", fontsize=11, fontweight="bold")
        ax.set_xlabel("Objetos Ordenados por Distância", fontsize=10)
        ax.set_ylabel(f"Distância ao {k_neighbor}º Vizinho Mais Próximo", fontsize=10)
        ax.grid(True, linestyle=":", alpha=0.6)

        # Heuristic elbow detection: choose percentile around 12% highest distances
        eps_heuristic = float(np.percentile(k_distances, 12))
        ax.axhline(eps_heuristic, color="red", linestyle="--", label=f"Eps calibrado: {eps_heuristic:.3f}")
        ax.legend(frameon=True, fontsize=9)

        # Run DBSCAN
        db = DBSCAN(eps=eps_heuristic, min_samples=k_neighbor)
        labels = db.fit_predict(X)

        n_clusters = len(set(labels)) - (1 if -1 in labels else 0)
        n_noise = int((labels == -1).sum())
        noise_pct = n_noise / len(labels)

        # Silhouette of non-noise points
        valid_mask = labels != -1
        if n_clusters > 1 and valid_mask.sum() > n_clusters:
            sil_non_noise = float(silhouette_score(X[valid_mask], labels[valid_mask]))
        else:
            sil_non_noise = 0.0

        results[name] = {
            "eps": eps_heuristic,
            "min_samples": k_neighbor,
            "n_clusters": n_clusters,
            "n_noise": n_noise,
            "noise_pct": noise_pct,
            "silhouette_non_noise": sil_non_noise,
            "labels": labels,
        }
        print(f"  {name:10s} -> Eps={eps_heuristic:.3f}, MinPts={k_neighbor} | "
              f"Clusters: {n_clusters}, Outliers/Ruídos: {n_noise} ({noise_pct:.1%}), "
              f"Silhueta (sem ruído): {sil_non_noise:+.4f}")

    plt.tight_layout()
    fig.savefig(output_dir / "k_distance_graph.png", dpi=200, bbox_inches="tight")
    plt.close(fig)

    return results


