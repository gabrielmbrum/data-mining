# ==========================================
# MAIN EXECUTION PIPELINE
# ==========================================


def run_clustering_pipeline(
    encoding_dir: Path,
    output_dir: Path,
    target_window: int = 32,
    k_optimal: int = 4,
) -> None:
    """
    Executes the complete Activity 4 clustering workflow:
    1. Loads window dataset
    2. Generates feature spaces (1D and 2D with PCA)
    3. Evaluates K-Means grid (SSE, Silhouette, DB) across K in [2, 7]
    4. Evaluates DBSCAN with k-distance graph
    5. Profiles archetypes for optimal K
    6. Generates medoid image visualizations
    """
    print(f"\n=======================================================")
    print(f"STARTING ACTIVITY 4 CLUSTERING PIPELINE (WINDOW {target_window}M)")
    print(f"=======================================================")

    window_dir = encoding_dir / f"window_{target_window:02d}"
    data = load_window_data(window_dir)
    features = prepare_feature_spaces(data, pca_variance=0.95)

    clustering_out = output_dir / "clustering"
    clustering_out.mkdir(parents=True, exist_ok=True)

    # 1. K-Means grid evaluation
    metrics_file = clustering_out / "kmeans_validation_metrics.parquet"
    if metrics_file.exists():
        print(f"Loading existing metrics from {metrics_file}...")
        df_metrics = pl.read_parquet(metrics_file)
    else:
        df_metrics = evaluate_kmeans_grid(features, k_range=range(2, 8), run_dtw=True)
        df_metrics.write_parquet(metrics_file)
        df_metrics.write_csv(clustering_out / "kmeans_validation_metrics.csv")

    plot_validation_metrics(df_metrics, clustering_out)

    # 2. DBSCAN execution
    dbscan_res = calibrate_and_run_dbscan(features, clustering_out, k_neighbor=5)

    # 3. Fit optimal K-Means models for deep profiling
    print(f"\n--- Profiling Depreciation Archetypes at K={k_optimal} ---")
    
    # Baseline 1D Euclidean
    km_1d_euc = KMeans(n_clusters=k_optimal, random_state=42, n_init=10).fit(features["1D_VRR"])
    df_prof_1d = profile_archetypes(
        data["series_vrr"],
        km_1d_euc.labels_,
        data["metadata"],
        "1D Euclidean",
        clustering_out,
    )

    # Baseline 1D DTW
    print("Fitting TimeSeriesKMeans DTW for profiling...")
    km_1d_dtw = TimeSeriesKMeans(
        n_clusters=k_optimal,
        metric="dtw",
        max_iter=15,
        random_state=42,
        n_jobs=-1,
    ).fit(features["1D_VRR"])
    df_prof_dtw = profile_archetypes(
        data["series_vrr"],
        km_1d_dtw.labels_,
        data["metadata"],
        "1D DTW",
        clustering_out,
    )

    # 2D GASF
    km_2d_gasf = KMeans(n_clusters=k_optimal, random_state=42, n_init=10).fit(features["2D_GASF"])
    df_prof_gasf = profile_archetypes(
        data["series_vrr"],
        km_2d_gasf.labels_,
        data["metadata"],
        "2D GASF",
        clustering_out,
    )

    # Combine summary profiles
    df_profiles = pl.concat([df_prof_1d, df_prof_dtw, df_prof_gasf])
    df_profiles.write_parquet(clustering_out / "archetypes_summary.parquet")
    df_profiles.write_csv(clustering_out / "archetypes_summary.csv")

    # 4. Medoid image examples
    plot_cluster_medoid_examples(
        data,
        km_2d_gasf.labels_,
        "2D GASF",
        clustering_out / "medoids_gasf_k4.png",
    )

    print("\nActivity 4 clustering pipeline executed successfully!")
    print(f"All figures and summary tables exported to: {clustering_out}")


if __name__ == "__main__":
    BASE_DIR = Path(__file__).resolve().parent.parent
    ENCODING_DIR = BASE_DIR / "output" / "encoding"
    OUTPUT_DIR = BASE_DIR / "output"

    run_clustering_pipeline(ENCODING_DIR, OUTPUT_DIR, target_window=32, k_optimal=4)
