def plot_cluster_medoid_examples(
    data: dict,
    labels: np.ndarray,
    method_name: str,
    output_path: Path,
) -> None:
    """
    Finds the medoid (vehicle closest to cluster centroid) for each cluster and
    plots its VRR curve alongside its GASF, GADF and MTF images.
    """
    unique_clusters = sorted([c for c in np.unique(labels) if c != -1])
    n_clusters = len(unique_clusters)
    window = data["series_vrr"].shape[1]
    months = np.arange(window)

    fig, axes = plt.subplots(n_clusters, 4, figsize=(14, 3.2 * n_clusters), squeeze=False)

    for r, c in enumerate(unique_clusters):
        c_mask = labels == c
        c_indices = np.flatnonzero(c_mask)
        c_series = data["series_vrr"][c_mask]

        # Centroid
        centroid = np.mean(c_series, axis=0)
        # Medoid: index with min distance to centroid
        dist_to_centroid = np.linalg.norm(c_series - centroid, axis=1)
        medoid_idx = c_indices[np.argmin(dist_to_centroid)]
        row = data["metadata"].row(medoid_idx, named=True)

        fuel_display = FUEL_MAP.get(row["sigla_combustivel"], row["sigla_combustivel"])
        model_name = row["nome_modelo"]
        if len(model_name) > 22:
            model_name = model_name[:19] + "..."

        # VRR Series
        ax_vrr = axes[r, 0]
        ax_vrr.plot(months, data["series_vrr"][medoid_idx] * 100, color="black", linewidth=2.0)
        ax_vrr.axhline(100.0, color="gray", linestyle="--", linewidth=0.9)
        ax_vrr.set_ylabel(
            f"Cluster {c+1}\n{row['segmento_preco']} | {fuel_display}\n{model_name}",
            fontsize=9,
            fontweight="bold",
        )
        ax_vrr.grid(True, linestyle=":", alpha=0.6)
        if r == 0:
            ax_vrr.set_title("Série VRR (%)", fontsize=11, fontweight="bold")
        if r == n_clusters - 1:
            ax_vrr.set_xlabel("Idade (Meses)", fontsize=9)

        # 2D Images
        panels = [
            (data["gasf"][medoid_idx], -1.0, 1.0, "GASF"),
            (data["gadf"][medoid_idx], -1.0, 1.0, "GADF"),
            (data["mtf"][medoid_idx], 0.0, 1.0, "MTF"),
        ]
