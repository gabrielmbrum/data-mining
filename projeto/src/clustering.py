def load_window_data(window_dir: Path) -> dict:
    """
    Loads all data artifacts generated by Activity 3 for a given window.
    """
    print(f"Loading data from {window_dir}...")
    with open(window_dir / "config.json", "r", encoding="utf-8") as f:
        config = json.load(f)

    series_vrr = np.load(window_dir / "series_vrr.npy")  # (N, T)
    gasf = np.load(window_dir / "gasf.npy")              # (N, T, T)
    gadf = np.load(window_dir / "gadf.npy")              # (N, T, T)
    mtf = np.load(window_dir / "mtf.npy")                # (N, T, T)
    metadata = pl.read_parquet(window_dir / "metadata.parquet")

    return {
        "config": config,
        "series_vrr": series_vrr,
        "gasf": gasf,
        "gadf": gadf,
        "mtf": mtf,
        "metadata": metadata,
    }


def prepare_feature_spaces(data: dict, pca_variance: float = 0.95) -> dict:
    """
    Extracts and prepares 1D and 2D feature representations.

    For 2D matrices, flattens the (T, T) images and fits PCA retaining
    'pca_variance' fraction of total variance, which eliminates high-frequency noise
    and structural colinearities.
    """
    n_vehicles = len(data["series_vrr"])
    features = {
        "1D_VRR": data["series_vrr"],
    }

    # Flatten 2D matrices
    gasf_flat = data["gasf"].reshape(n_vehicles, -1)
    gadf_flat = data["gadf"].reshape(n_vehicles, -1)
    mtf_flat = data["mtf"].reshape(n_vehicles, -1)
    multi_flat = np.concatenate([gasf_flat, gadf_flat, mtf_flat], axis=1)

    print("\nApplying PCA to 2D representations (variance threshold: "
          f"{pca_variance:.0%})...")

    for name, matrix in [
        ("2D_GASF", gasf_flat),
        ("2D_GADF", gadf_flat),
        ("2D_MTF", mtf_flat),
        ("2D_Multichannel", multi_flat),
    ]:
        pca = PCA(n_components=pca_variance, random_state=42)
        projected = pca.fit_transform(matrix)
        features[name] = projected
        print(f"  {name:16s}: Original dim {matrix.shape[1]:4d} -> "
              f"Reduced dim {projected.shape[1]:3d} "
              f"({pca.n_components_} components, {pca.explained_variance_ratio_.sum():.1%} variance)")

    return features


