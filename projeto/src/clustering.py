def profile_archetypes(
    series: np.ndarray,
    labels: np.ndarray,
    metadata: pl.DataFrame,
    method_name: str,
    output_dir: Path,
) -> pl.DataFrame:
    """
    Profiles each cluster to characterize its financial depreciation archetype:
    - Average VRR trajectory with IQR / std band
    - Fuel and segment distributions
    - Descriptive statistics table
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    unique_clusters = sorted([c for c in np.unique(labels) if c != -1])
    n_clusters = len(unique_clusters)
    window = series.shape[1]
    months = np.arange(window)

    meta_with_labels = metadata.with_columns(pl.Series("cluster", labels))

    # 1. Trajectory curves
    fig, axes = plt.subplots(1, n_clusters, figsize=(4.2 * n_clusters, 4.0), sharey=True)
    if n_clusters == 1:
        axes = [axes]

    colors = ["#1f77b4", "#ff7f0e", "#2ca02c", "#d62728", "#9467bd", "#8c564b"]
    summary_rows = []

    for idx, c in enumerate(unique_clusters):
        c_mask = labels == c
        c_series = series[c_mask] * 100.0  # Percentage
        n_items = len(c_series)
        color = colors[idx % len(colors)]

        mean_traj = np.mean(c_series, axis=0)
        q25 = np.percentile(c_series, 25, axis=0)
        q75 = np.percentile(c_series, 75, axis=0)

        vrr_init = mean_traj[0]
        vrr_12m = mean_traj[12] if window > 12 else mean_traj[-1]
        vrr_end = mean_traj[-1]
        delta_vrr = vrr_end - vrr_init

        # Fuel distribution in cluster
        c_meta = meta_with_labels.filter(pl.col("cluster") == c)
        ev_count = c_meta.filter(pl.col("sigla_combustivel") == "l").height
        hybrid_count = c_meta.filter(pl.col("sigla_combustivel") == "h").height
        ice_count = n_items - ev_count - hybrid_count

        summary_rows.append({
            "metodo": method_name,
            "cluster": f"Cluster {c+1}",
            "n_veiculos": n_items,
            "pct_total": n_items / len(labels),
            "vrr_inicial_pct": vrr_init,
            "vrr_12m_pct": vrr_12m,
            "vrr_final_pct": vrr_end,
            "variacao_liquida_pct": delta_vrr,
            "n_eletricos": ev_count,
            "n_hibridos": hybrid_count,
            "n_combustao": ice_count,
            "pct_eletrificados": (ev_count + hybrid_count) / n_items if n_items > 0 else 0.0,
        })

        ax = axes[idx]
        ax.plot(months, mean_traj, color=color, linewidth=2.2, label="Trajetória Média")
        ax.fill_between(months, q25, q75, color=color, alpha=0.25, label="Intervalo Interquartil (Q1-Q3)")
        ax.axhline(100.0, color="gray", linestyle="--", linewidth=1.0, alpha=0.7)

        ax.set_title(f"Cluster {c+1} (n={n_items:,})", fontsize=11, fontweight="bold")
        ax.set_xlabel("Idade do Ativo (Meses)", fontsize=10)
        if idx == 0:
            ax.set_ylabel("VRR (%)", fontsize=10)
        ax.grid(True, linestyle=":", alpha=0.6)
        if idx == 0:
            ax.legend(frameon=True, fontsize=8, loc="upper right")

    plt.suptitle(f"Arquétipos de Depreciação - {method_name}", fontsize=13, fontweight="bold", y=1.02)
    plt.tight_layout()
    fig.savefig(output_dir / f"archetypes_trajectories_{method_name.lower().replace(' ', '_').replace('(', '').replace(')', '')}.png",
                dpi=200, bbox_inches="tight")
    plt.close(fig)

    # 2. Composition by fuel and price segment
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12, 4.5))

    # Fuel stack
    fuel_df = (
        meta_with_labels.filter(pl.col("cluster") != -1)
        .group_by(["cluster", "sigla_combustivel"])
        .len()
        .sort(["cluster", "sigla_combustivel"])
    )
    
    cluster_names = [f"C{c+1}" for c in unique_clusters]
    fuel_types = ["l", "h", "f", "g", "d"]
    fuel_labels = ["Elétrico", "Híbrido", "Flex", "Gasolina", "Diesel"]

    bottoms = np.zeros(n_clusters)
    for f_code, f_name in zip(fuel_types, fuel_labels):
        heights = []
        for c in unique_clusters:
            row = fuel_df.filter((pl.col("cluster") == c) & (pl.col("sigla_combustivel") == f_code))
            cnt = row["len"][0] if row.height > 0 else 0
            total_in_c = (labels == c).sum()
            heights.append(cnt / total_in_c if total_in_c > 0 else 0)
        heights = np.array(heights)
        ax1.bar(cluster_names, heights, bottom=bottoms, label=f_name, color=FUEL_COLORS.get(f_name, "#333333"))
        bottoms += heights

    ax1.set_title("Distribuição por Matriz Energética", fontsize=11, fontweight="bold")
    ax1.set_ylabel("Proporção no Cluster", fontsize=10)
    ax1.set_ylim(0, 1.0)
    ax1.legend(frameon=True, fontsize=9, loc="upper right")
    ax1.grid(True, linestyle=":", alpha=0.6, axis="y")

    # Segment stack
    seg_df = (
        meta_with_labels.filter(pl.col("cluster") != -1)
        .group_by(["cluster", "segmento_preco"])
        .len()
        .sort(["cluster", "segmento_preco"])
    )
    seg_types = ["Entrada", "Intermediario", "Luxo"]
    bottoms_seg = np.zeros(n_clusters)
    for seg_name in seg_types:
        heights_seg = []
        for c in unique_clusters:
            row = seg_df.filter((pl.col("cluster") == c) & (pl.col("segmento_preco") == seg_name))
            cnt = row["len"][0] if row.height > 0 else 0
            total_in_c = (labels == c).sum()
            heights_seg.append(cnt / total_in_c if total_in_c > 0 else 0)
        heights_seg = np.array(heights_seg)
        ax2.bar(cluster_names, heights_seg, bottom=bottoms_seg, label=seg_name, color=SEGMENT_COLORS.get(seg_name, "#333333"))
        bottoms_seg += heights_seg

    ax2.set_title("Distribuição por Faixa de Preço de Lançamento", fontsize=11, fontweight="bold")
    ax2.set_ylabel("Proporção no Cluster", fontsize=10)
    ax2.set_ylim(0, 1.0)
    ax2.legend(frameon=True, fontsize=9, loc="upper right")
    ax2.grid(True, linestyle=":", alpha=0.6, axis="y")

    plt.suptitle(f"Composição dos Agrupamentos - {method_name}", fontsize=12, fontweight="bold", y=1.02)
    plt.tight_layout()
    fig.savefig(output_dir / f"composition_{method_name.lower().replace(' ', '_').replace('(', '').replace(')', '')}.png",
                dpi=200, bbox_inches="tight")
    plt.close(fig)

    return pl.DataFrame(summary_rows)


