def evaluate_kmeans_grid(
    features: dict,
    k_range: range = range(2, 8),
    run_dtw: bool = True,
    random_state: int = 42,
) -> pl.DataFrame:
    """
    Evaluates K-Means clustering across a range of K for 1D (Euclidean and DTW)
    and 2D representations.

    Returns a Polars DataFrame containing SSE/inertia, Silhouette Score,
    Davies-Bouldin Score and execution time.
    """
    records = []
    print("\n--- Running K-Means Grid Evaluation ---")

    # Evaluate standard vector representations
    for name, X in features.items():
        print(f">> Evaluating {name} across K in {list(k_range)}...")
        for k in k_range:
            t0 = time.time()
            km = KMeans(n_clusters=k, random_state=random_state, n_init=10)
            labels = km.fit_predict(X)
            elapsed = time.time() - t0

            sil = float(silhouette_score(X, labels))
            db = float(davies_bouldin_score(X, labels))
            sse = float(km.inertia_)

            records.append({
                "representation": name,
                "k": k,
                "sse": sse,
                "silhouette": sil,
                "davies_bouldin": db,
                "time_sec": elapsed,
            })
            print(f"  K={k}: SSE={sse:.2f} | Sil={sil:+.4f} | DB={db:.4f} ({elapsed:.2f}s)")

    # Evaluate 1D DTW using TimeSeriesKMeans
    if run_dtw:
        X_1d = features["1D_VRR"]
        print(f">> Evaluating 1D_VRR (DTW) across K in {list(k_range)}...")
        for k in k_range:
            t0 = time.time()
            km_dtw = TimeSeriesKMeans(
                n_clusters=k,
                metric="dtw",
                max_iter=15,
                random_state=random_state,
                n_jobs=-1,
            )
            labels = km_dtw.fit_predict(X_1d)
            elapsed = time.time() - t0

            # Evaluate silhouette in Euclidean space of series for direct comparison
            sil = float(silhouette_score(X_1d, labels))
            db = float(davies_bouldin_score(X_1d, labels))
            sse = float(km_dtw.inertia_)

            records.append({
                "representation": "1D_VRR (DTW)",
                "k": k,
                "sse": sse,
                "silhouette": sil,
                "davies_bouldin": db,
                "time_sec": elapsed,
            })
            print(f"  K={k} (DTW): SSE={sse:.2f} | Sil={sil:+.4f} | DB={db:.4f} ({elapsed:.2f}s)")

    return pl.DataFrame(records)


